//! 全文搜索（PLAN.md §3.4 M2-C「全局搜索」）。
//!
//! 三个 crate 分工明确，都是 ripgrep 的库化产物（Unlicense OR MIT）：
//! `ignore` 负责「走哪些文件」（含 .gitignore 过滤），`grep-regex` 负责「编一台匹配机」，
//! `grep-searcher` 负责「按行扫正文」。本模块把它们接成一条**流式**的搜索。
//!
//! ## ⚠️ 这里按 .gitignore 过滤，而文件树不过滤——方向刻意相反
//!
//! `project::tree` 的模块文档里写着「不按 .gitignore 过滤」，本模块恰恰相反，
//! 而且两边各有一条钉住自己方向的测试（那边是 `gitignore_命中的条目照常列出`，
//! 这边是 `gitignore_命中的文件不搜`）。**两条测试方向相反不是写错了，是两处的成本
//! 结构不同**：
//!
//! - 树是**按需**的，一次只读用户点开的那一层，成本与仓库里有多少文件无关。过滤省下的是
//!   本来就没花的钱，自己却要先读一遍 .gitignore 链、编成 regex set——实测顶层慢 45×。
//! - 搜索要把**每个文件的正文都读一遍**，成本与文件数成正比。这时 .gitignore 才真正省钱：
//!   不过滤就等于 grep 十万个 `node_modules` 里的文件。
//!
//! ## ⚠️ 符号链接也是反的：树放行，搜索不跟随
//!
//! 树放行链接是因为「展开一层」的成本有限，而 pnpm 的 `node_modules` 整个是符号链接搭的，
//! 挡住它等于让本项目不能用。搜索要读正文，跟着链接走会把同一个包读几十遍，
//! 还可能成环（`WalkBuilder` 有环检测，但代价是每次都要比 inode）。
//! 所以这里 `follow_links(false)`，并且只搜 `file_type().is_file()` 的条目——
//! 链接自己的 `file_type` 既不是 file 也不是 dir，于是被一并跳过。
//!
//! ## 为什么是流式，以及批次多大
//!
//! PLAN §2.6 约束 1 与 3：单次 IPC payload 上限 4MB，长任务一律 `taskId` + event 推进度。
//! 一次搜索在十万文件的仓库上可以产出上万条命中，一次性回传既撞 4MB 也撞
//! 「首批结果 < 2s」那条验收——所以每攒够 `BATCH_FILES` 个文件或 `BATCH_HITS` 条命中
//! 就推一批。批次的**单位是文件**：一个文件的命中只有在扫完它之后才齐，
//! 而 UI 是按文件分组的，半份文件的命中没有意义。
//!
//! ## 为什么是单线程遍历
//!
//! `ignore` 有 `build_parallel`，ripgrep 用的就是它。这里刻意用单线程的 `build()`：
//! ① 取消与截断都是「走到哪儿停到哪儿」，并行版本要额外协调谁先停；
//! ② **结果顺序确定**，同一棵树搜两次长得一样，测试才写得出来（并行版本的顺序随线程调度漂）；
//! ③ 流式推送让**有命中时**的「首批 < 2s」不依赖总耗时。真要提速，换 `build_parallel`
//! 是一个局部改动。
//!
//! ## ⚠️ 一个都不命中时，「首批」根本不是结果——所以要心跳
//!
//! 上面第 ③ 条只对有命中的搜索成立。实测（十万个文件、外部卷、release）：
//!
//! | 场景 | 首批延迟 | 总耗时 |
//! |---|---|---|
//! | 有 2000 处命中 | **65.6ms** | 6.93s |
//! | 一个都不命中 | **7.14s** | 7.14s |
//!
//! 第二行是这一节存在的全部理由：批次以「有命中的文件」为单位，于是**没有命中就没有批次**，
//! 前端在 7.14 秒里手上什么都没有——既不能显示进度，也不能说「没找到」，看起来就是卡死了。
//! 而「搜一个不存在的词」恰恰是全文搜索最常见的操作之一。
//!
//! 解法是让 `SearchBatch` 允许 `files` 为空：那是一个**心跳**，只带累计的 `files_scanned`。
//! 两条阈值取先到者——每 `HEARTBEAT_FILES` 个文件，或距上次推送过了 `HEARTBEAT_MS`——
//! 于是前端最多 250ms 或 256 个文件收不到信号，与仓库里文件的平均大小无关。
//!
//! 加上心跳之后同一棵树复测：**第一个信号 33.75ms**（原来 7.14s，快了约 218 倍），
//! 全程 390 次心跳，相邻两次之间最长静默 **40.3ms**，总耗时 7.35s 基本没变
//! （390 个几十字节的批次对 7 秒的遍历来说是噪音）。
//!
//! **前端的规则因此是：`files` 为空时只更新进度，不要动结果列表，更不要把它当成
//! 「搜索结束了」。**结束的唯一信号是命令返回的 `SearchSummary`。
//!
//! ## 命中行的偏移量是 UTF-16 码元，不是字符也不是字节
//!
//! [`MatchRange`] 里的 `start`/`end` 数的是 UTF-16 码元。这不是顺手抄了 JS 的习惯，
//! 而是因为**消费方是 CodeMirror**：它的位置就是 UTF-16 码元偏移。Rust 侧发字符偏移的话，
//! 前端得再转一次，而那次转换的失败方式是「高亮画错一个字」——在含 emoji 或
//! CJK 扩展区（`𠀀` 这类，一个字符两个码元）的行上必错，而错得很安静。
//! 在产出偏移量的那一侧一次算对，比在消费侧到处补转换便宜。
//!
//! ## 二进制文件与非 UTF-8 文件：两条相反的取舍
//!
//! 这两类文件长得像，处理方式却必须相反，所以放在一起说清楚。
//!
//! - **含 NUL 的（二进制）**：`quit(0)`，见到 NUL 就收手。这一条是**显式配上去的**，
//!   不是继承来的默认值——`Searcher::new()` 拿到 `\x00\xff\nneedle\n` 照样把 `needle`
//!   报出来，钉这件事的测试在配上它之前是红的。不猜第三方库的默认值，是因为猜错的
//!   失败方式很安静：搜索结果里混进 `.woff2`、`.png`、`pack-*.idx`，而它们全都
//!   「看起来像个文件」。
//! - **不含 NUL 但也不是 UTF-8 的（GBK 之类）**：走 `sinks::Lossy`，非法字节换成 U+FFFD
//!   继续搜。用 `sinks::UTF8` 的话这个文件会让 `search_path` 报错，于是被计入
//!   `unreadable` 而**一条命中都不报**——用户搜一个明明在文件里的标识符，
//!   得到「0 个结果」加一句「有 1 个文件读不出来」，而那个文件正是他要的。
//!   Vela 的目标用户会打开 GBK 文件（`fs` 那边专门做了编码探测），这不是边角情况。
//!
//! ⚠️ 两条各有一个诚实的限制，都记在钉住它们的测试上：
//! Lossy 换来的是「ASCII 搜索词（标识符、URL、错误码）在 GBK 文件里照样命中」，
//! 代价是**中文搜索词搜不到非 UTF-8 文件里的中文**（字节序列不同，要支持得先按探测出的
//! 编码把整个文件解码一遍，那是另一件事）；`quit` 的收手粒度是按读缓冲来的，
//! 而 `search_path` 返回 `()`、给不出「有没有搜完」的信号，所以被收手的文件
//! `truncated` 仍然是 false。见 `空字符在第一个缓冲里时整个文件不报_在很后面时之前的命中留着`
//! 与 `非纯文本编码的文件走有损解码_英文搜索词照样命中`。
//!
//! ## 每一个 `SearchError` 都发生在第一批结果之前
//!
//! 这是刻意维持的性质：编译正则、编译通配、检查 root 三件事全在遍历开始之前做完。
//! 于是前端的规则可以很简单——`start_search` reject 了就是「这次搜索压根没开始」，
//! 收到了 event 就是「搜索开始了，剩下的只会是 done」。
//! 遍历途中的单个文件读不动**不是**错误：它计入 [`SearchSummary::unreadable`]，
//! 搜索继续。整次搜索失败比少搜一个目录糟得多。

